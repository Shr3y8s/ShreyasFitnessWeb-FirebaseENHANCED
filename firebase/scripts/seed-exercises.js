// Main execution function
async function seedExercises() {
  console.log('🌱 Starting exercise library seed...\n');
  console.log(`📝 User ID: ${userId}`);
  console.log(`👤 User Name: ${userName}`);
  console.log(`📊 Total exercises to add: ${exercises.length}\n`);

  const timestamp = admin.firestore.FieldValue.serverTimestamp();
  let successCount = 0;
  let errorCount = 0;

  for (let i = 0; i < exercises.length; i++) {
    const exercise = exercises[i];
    
    try {
      // Create exercise document
      const exerciseData = {
        ...exercise,
        createdBy: userId,
        createdByName: userName,
        createdAt: timestamp,
        updatedAt: timestamp,
        isActive: true,
        usageCount: 0
      };

      await db.collection('exercises').add(exerciseData);
      successCount++;
      console.log(`✅ [${i + 1}/${exercises.length}] Added: ${exercise.name}`);
      
    } catch (error) {
      errorCount++;
      console.error(`❌ [${i + 1}/${exercises.length}] Failed: ${exercise.name}`, error.message);
    }
  }

  console.log('\n🎉 Seed completed!');
  console.log(`✅ Successfully added: ${successCount} exercises`);
  if (errorCount > 0) {
    console.log(`❌ Failed: ${errorCount} exercises`);
  }
  console.log('\n📚 Your exercise library is now ready to use!');
  
  process.exit(0);
}

// Run the seed
seedExercises().catch((error) => {
  console.error('❌ Fatal error:', error);
  process.exit(1);
});
